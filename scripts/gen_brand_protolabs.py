"""Regenerate the protoLabs brand snapshot (``brands/protolabs/``) from the design system.

The video end-card recipe renders OFFLINE (no network at render time), so the protoLabs look is
a checked-in SNAPSHOT of the ``@protolabsai/design`` tokens at a pinned version — never hand-
picked values. Run it against an installed copy of the package (the console's, or a fresh
``npm pack @protolabsai/design@<version>`` extracted into a scratch dir)::

    python scripts/gen_brand_protolabs.py --design <path to the @protolabsai/design package dir>
    python scripts/gen_brand_protolabs.py --check     # CI/test: the kit still matches tokens.json

It copies ``dist/tokens.json`` and the mark (``assets/protolabs-icon-outline.svg``) into
``brands/protolabs/`` and writes ``brand-kit.yaml`` from them with ``build_kit`` — the ONE token →
brand-kit mapping (the suite re-runs it on the checked-in tokens to catch drift). The fonts
(Geist / Geist Mono variable woff2 + their SIL OFL licence, from the ``geist`` npm package) are
vendored beside it: the DS itself only links Google Fonts, which a card can't load.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "brands" / "protolabs"
FONTS = {"Geist": "fonts/Geist-Variable.woff2", "Geist Mono": "fonts/GeistMono-Variable.woff2"}
FONT_SOURCE = "geist@1.3.1 (npm, SIL OFL 1.1 — fonts/OFL.txt)"


def _family(stack: str) -> str:
    """The first family of a CSS font stack: '"Geist", system-ui, …' → 'Geist'."""
    return stack.split(",")[0].strip().strip("\"'")


def build_kit(tokens: dict, version: str, tokens_sha256: str) -> dict:
    """``@protolabsai/design`` tokens → a Campaign Studio brand kit (the explicit mapping)."""
    c, f = tokens["color"], tokens["font"]
    w = f["weight"]
    sans, mono = _family(f["sans"]), _family(f["mono"])
    return {
        "name": "protoLabs",
        "source": {
            "package": "@protolabsai/design",
            "version": version,
            "tokens_sha256": tokens_sha256,
            "fonts": FONT_SOURCE,
            "regenerate": "python scripts/gen_brand_protolabs.py --design <@protolabsai/design dir>",
        },
        "visual": {
            "wordmark": "protoLabs",
            # card slot ← DS token
            "colors": {
                "background": c["bg"],  # --pl-color-bg
                "foreground": c["fg"],  # --pl-color-fg
                "accent": c["accent"],  # --pl-color-accent (brand lavender)
                "muted": c["fgMuted"],  # --pl-color-fg-muted
            },
            "fonts": {
                "heading": sans,  # --pl-font-sans
                "body": sans,
                "mono": mono,  # --pl-font-mono
                "files": [{"family": fam, "path": FONTS[fam], "weight": "100 900"} for fam in (sans, mono)],
            },
            "logo": {"path": "protolabs-icon-outline.svg"},
            # The large-format VIDEO END-CARD recipe (cta-slide / title-slide at 1080p–2K):
            # DS weight stops, the primary button's bordered-rectangle identity (stronger
            # border, base radius, no fill, no glow) and the restrained 8 % brand glow.
            "card": {
                "button": "outline",
                "background": "subtle",
                "title_weight": int(w["semibold"]),  # --pl-font-weight-semibold
                "eyebrow_weight": int(w["medium"]),  # --pl-font-weight-medium
                "button_weight": int(w["medium"]),
                "body_weight": int(w["body"]),  # --pl-font-weight-body
                "radius_px": int(str(tokens["radius"]).rstrip("px")),  # --pl-radius, at 1280 px wide
                "border_px": int(str(tokens["borderWidth"]).rstrip("px")),  # --pl-border-width, at 1280 px wide
            },
        },
    }


def _dump(kit: dict) -> str:
    import yaml

    head = "# GENERATED by scripts/gen_brand_protolabs.py from @protolabsai/design tokens — do not edit by hand.\n"
    return head + yaml.safe_dump(kit, sort_keys=False, allow_unicode=True)


def generate(design: Path) -> None:
    pkg = json.loads((design / "package.json").read_text())
    if pkg.get("name") != "@protolabsai/design":
        sys.exit(f"{design} is not the @protolabsai/design package")
    raw = (design / "dist" / "tokens.json").read_bytes()
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "ds-tokens.json").write_bytes(raw)
    (OUT / "ds-version.txt").write_text(pkg["version"] + "\n")
    shutil.copyfile(design / "assets" / "protolabs-icon-outline.svg", OUT / "protolabs-icon-outline.svg")
    kit = build_kit(json.loads(raw), pkg["version"], hashlib.sha256(raw).hexdigest())
    (OUT / "brand-kit.yaml").write_text(_dump(kit), encoding="utf-8")
    print(f"wrote {OUT / 'brand-kit.yaml'} from @protolabsai/design@{pkg['version']}")


def check() -> str:
    """'' when brand-kit.yaml is exactly what the checked-in tokens produce, else why not."""
    raw = (OUT / "ds-tokens.json").read_bytes()
    version = (OUT / "ds-version.txt").read_text().strip()
    want = _dump(build_kit(json.loads(raw), version, hashlib.sha256(raw).hexdigest()))
    have = (OUT / "brand-kit.yaml").read_text(encoding="utf-8")
    return "" if want == have else "brands/protolabs/brand-kit.yaml drifted from ds-tokens.json — regenerate it"


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--design", type=Path)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        problem = check()
        print(problem or "brand snapshot is current")
        sys.exit(1 if problem else 0)
    if not a.design:
        sys.exit("--design <path to @protolabsai/design> (or --check)")
    generate(a.design)
